//! Подробный контент страниц услуг.
//!
//! Каталог `/services` отвечает на вопрос «что вы делаете и сколько это стоит».
//! Страница услуги отвечает на следующий: «подходит ли это мне, что войдёт в
//! работу и как она будет идти». Поэтому текст здесь не повторяет описание из
//! карточки, а раскрывает результат, состав работы, ограничения и вопросы,
//! которые обычно задают до старта.
//!
//! Слаги совпадают со [`crate::memory::content::Service::slug`]. Это проверяет
//! тест в конце файла: если услуга появилась в каталоге без страницы или
//! страница осталась без услуги, сборка тестов падает.

/// Шаг работы: короткое название и объяснение.
pub type Step = (&'static str, &'static str);

/// Вопрос и ответ для блока «Вопросы».
pub type Faq = (&'static str, &'static str);

/// Содержимое одной страницы услуги.
#[derive(Debug, Clone, Copy)]
pub struct ServicePage {
    pub slug: &'static str,
    /// Надзаголовок: категория и характер работы.
    pub kicker: &'static str,
    /// Формат работы для строки характеристик.
    pub format: &'static str,
    /// Один или два абзаца под заголовком.
    pub lead: &'static str,
    /// Главный результат одной строкой.
    pub result: &'static str,
    /// Что получает клиент. Три пункта, каждый начинает строку.
    pub outcomes: &'static [&'static str],
    /// Что входит в работу.
    pub includes: &'static [&'static str],
    /// Как идёт работа.
    pub steps: &'static [Step],
    /// Кому подходит.
    pub fit: &'static [&'static str],
    /// Когда лучше не начинать.
    pub not_for: &'static [&'static str],
    /// Частые вопросы.
    pub faq: &'static [Faq],
    /// Инструменты и навыки, которые видны в работе.
    pub skills: &'static [&'static str],
    /// Похожие услуги: слаги из каталога.
    pub related: &'static [&'static str],
    /// Подходящие кейсы: слаги из `SiteContent::projects`.
    pub projects: &'static [&'static str],
}

