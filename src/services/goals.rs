//! Идентификаторы целей аналитики.
//!
//! Цель в этом проекте — это строка, которую страница отправляет счётчикам:
//! `ym(…, 'reachGoal', …)` в Метрике и `gtag('event', …)` в GA4. Строка одна на
//! оба счётчика: одинаковое имя цели в двух панелях — единственный способ
//! сравнить их цифры, не сверяя на глаз, что «Заявка» в Метрике и
//! `lead_submitted` в GA4 — это одно и то же событие.
//!
//! Разметку и скрипт связывает атрибут, а не код: `data-goal="имя"` на ссылке,
//! кнопке или форме и `data-goal-read="имя"` на блоке, который считается
//! прочитанным. `assets/main.js` берёт значение атрибута и отправляет его как
//! имя цели, поэтому новая цель — это один атрибут в разметке и строка в
//! интерфейсе Метрики, без правки скрипта. Здесь лежат только сами имена:
//! их печатает `docs/seo-toolkit.md`, из них же собирается тест, который
//! проверяет, что каждая цель где-то в разметке есть.
//!
//! Почему цели на странице, а не в конструкторе Метрики: конструктор целей
//! открывает сайт в своём фрейме и на этом падает («Ошибка при загрузке
//! страницы»), а цели типа «JavaScript-событие» задаются одним текстовым
//! полем и работают независимо от того, открывается ли сайт у Метрики в
//! интерфейсе.

/// Отправка формы заявки на `/contact` — и только успешная (2xx).
pub const LEAD_SUBMITTED: &str = "lead_submitted";

/// Первое сообщение в чате: страница `/chat` или терминал на главной.
pub const CHAT_STARTED: &str = "chat_started";

/// Переход в Telegram (подвал и страница контактов).
pub const TG_CLICK: &str = "tg_click";

/// Клик по `mailto:` — почта вместо мессенджера.
pub const EMAIL_CLICK: &str = "email_click";

/// Переход во ВКонтакте со страницы контактов.
pub const VK_CLICK: &str = "vk_click";

/// 90 % высоты статьи: дочитал, а не пролистал начало.
///
/// Порог по блоку, а не по странице: у статьи с обложкой, подвалом и
/// комментариями «90 % страницы» наступает заметно позже, чем человек
/// действительно дочитал текст.
pub const ARTICLE_READ_90: &str = "article_read_90";

/// Все цели. Используется тестом, который сверяет список с разметкой: цель,
/// добавленная здесь и нигде не привязанная, — это пустая цель в интерфейсе
/// Метрики, и заметить это можно только по нулям через месяц.
pub const ALL: &[&str] = &[
    LEAD_SUBMITTED,
    CHAT_STARTED,
    TG_CLICK,
    EMAIL_CLICK,
    VK_CLICK,
    ARTICLE_READ_90,
];

#[cfg(test)]
mod tests {
    use super::*;

    /// Имя цели уезжает в разметку атрибутом и в JavaScript строковой
    /// константой. Алфавит узкий по той же причине, что у номера счётчика:
    /// кавычка в имени — это выход из строкового литерала в скрипте.
    #[test]
    fn goal_ids_are_safe_for_markup_and_javascript() {
        for goal in ALL {
            assert!(!goal.is_empty(), "пустое имя цели");
            assert!(
                goal.chars()
                    .all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '_'),
                "имя цели «{goal}» содержит символ вне [a-z0-9_]"
            );
        }
    }

    /// Дубликат в `ALL` — это две одинаковые цели в Метрике и удвоенная
    /// статистика в одной из них.
    #[test]
    fn goal_ids_are_unique() {
        let mut seen = ALL.to_vec();
        seen.sort_unstable();
        let before = seen.len();
        seen.dedup();
        assert_eq!(before, seen.len(), "в ALL есть повтор: {ALL:?}");
    }
}
