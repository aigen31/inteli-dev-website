//! Глоссарий: короткие объяснения терминов, которые встречаются на сайте.
//!
//! # Зачем отдельный модуль
//!
//! Человек не обязан знать, что такое MCP или локальный инференс. Раньше
//! объяснение уходило в языковую модель: каждый клик по термину стоил токенов,
//! ждал ответа и мог разойтись с тем, что написано на сайте.
//!
//! Здесь те же объяснения лежат готовыми. Кнопка показывает их сразу, без
//! запроса к серверу и без модели: ноль токенов, ноль ожидания, одинаковый
//! текст на всех поверхностях.
//!
//! Правило для текстов: два-три предложения, только факты, без обещаний и без
//! «оставьте заявку».

/// Термин и его объяснение.
pub struct Entry {
    /// Стабильный ключ (используется в `data-answer` и тестах).
    pub slug: &'static str,
    /// Подпись на кнопке.
    pub label: &'static str,
    /// Готовый ответ.
    pub answer: &'static str,
}

